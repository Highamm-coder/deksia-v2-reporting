-- 0037_retention_policy.sql — applied live 2026-08-27.
--
-- Context: the Meta metric expansion grew metrics_daily to 1.81M rows / 951 MB and
-- filled the project disk; Supabase flipped the database to read-only mid-backfill.
-- Immediate relief was dropping four unused indexes (entity/metric/client/source,
-- ~97 MB) and pruning 331,019 stale breakout rows. This migration makes the pruning
-- a standing policy so it cannot recur.
--
-- Retention horizons (Matt, 2026-08-27: "Last year, this year"):
--   history  — no grain kept before Jan 1 of the previous calendar year (rolling).
--   breakout — 'brk:%' qualifiers kept for a trailing 90 days only. They are
--              non-additive drill-down already excluded from every aggregation by
--              is_breakout(), and they were ~30% of all rows.
--
-- Deletes run one calendar month per statement: a single 331k-row delete is what
-- exhausted temp space in the first place.
--
-- Scheduled: pg_cron job 'metrics-retention', 40 9 * * * (before the 10:00 goal
-- tracker). VACUUM is deliberately NOT in the job — pg_cron wraps each command in a
-- transaction and VACUUM cannot run inside one; autovacuum picks it up from the
-- dead-tuple count.
--
-- The producing side matches: orchestrator/run.mjs skips the three breakout Graph
-- calls when the run window already ends outside the 90-day horizon (override with
-- WRITE_BREAKOUTS=1), so a backfill never writes rows the prune deletes hours later.
--
-- Full DDL lives in the applied migration of the same name; see prune_metrics().
